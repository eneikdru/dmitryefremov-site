export async function fetchEssaysFromApi(customFetch = fetch): Promise<EssayArticleItem[]> {
  try {
    const res = await customFetch('/api/v1/essays');
    if (!res.ok) return INITIAL_ESSAYS;
    const data = await res.json();
    const rawList = Array.isArray(data) ? data : (data?.content || []);
    if (rawList.length === 0) return INITIAL_ESSAYS;
    return rawList
      .filter((item: any) => {
        const title = (item.title || '').toLowerCase();
        const slug = (item.slug || '').toLowerCase();
        if (title.includes('teleprompter') || slug.includes('teleprompter') || title.includes('raw_') || title.includes('суфлёр')) {
          return false;
        }
        return true;
      })
      .map((item: any) => {
        return {
          id: item.slug || String(item.id),
          slug: item.slug || String(item.id),
          title: item.title || 'Отредактированное эссе',
          topic: (item.topic || 'systems') as any,
          readTime: item.readTime || '3 min read',
          publishedAt: item.publishedAt ? String(item.publishedAt).slice(0, 10) : '',
          summary: item.summary || '',
          contentMarkdown: item.content || item.summary || ''
        };
      });
  } catch {
    return INITIAL_ESSAYS;
  }
}

export async function fetchCanonFromApi(customFetch = fetch): Promise<any[]> {
  try {
    const res = await customFetch('/api/v1/canon');
    if (!res.ok) return [];
    const data = await res.json();
    return Array.isArray(data) ? data : (data?.content || []);
  } catch {
    return [];
  }
}

export function getLocalizedEssay(essay: EssayArticleItem, lang: Language): EssayArticleItem {
  if (lang === 'ru') return essay;
  const translations = ESSAYS_TRANSLATIONS[essay.id] || ESSAYS_TRANSLATIONS[essay.slug];
  if (!translations || !translations[lang]) return essay;
  const tr = translations[lang];
  return {
    ...essay,
    title: tr.title,
    summary: tr.summary,
    contentMarkdown: tr.contentMarkdown
  };
}
