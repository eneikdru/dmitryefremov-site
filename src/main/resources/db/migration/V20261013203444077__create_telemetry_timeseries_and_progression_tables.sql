CREATE TABLE telemetry_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type VARCHAR(100) NOT NULL,
    source VARCHAR(255),
    resource_id VARCHAR(255),
    metric_value DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    payload TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_telemetry_events_type_created ON telemetry_events (event_type, created_at DESC);

CREATE TABLE scrollytelling_progression (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource_id VARCHAR(255) NOT NULL UNIQUE,
    max_depth DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    total_depth DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    event_count BIGINT NOT NULL DEFAULT 0,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
