CREATE TABLE sparks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    telegram_message_id BIGINT UNIQUE,
    telegram_chat_id BIGINT,
    content TEXT NOT NULL,
    domain VARCHAR(100),
    tags VARCHAR(500),
    author VARCHAR(255),
    published_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_sparks_telegram_message_id ON sparks(telegram_message_id);
CREATE INDEX idx_sparks_published_at ON sparks(published_at);
CREATE INDEX idx_sparks_domain ON sparks(domain);
