CREATE TABLE IF NOT EXISTS concept_media_links (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canon_item_id BIGINT NOT NULL,
    media_type VARCHAR(50) NOT NULL,
    podcast_episode_id BIGINT,
    essay_id BIGINT,
    spark_id BIGINT,
    article_id BIGINT,
    relationship_type VARCHAR(50) NOT NULL DEFAULT 'DISCUSSES',
    description TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_concept_media_canon FOREIGN KEY (canon_item_id) REFERENCES canon_items(id) ON DELETE CASCADE,
    CONSTRAINT fk_concept_media_podcast FOREIGN KEY (podcast_episode_id) REFERENCES podcast_episodes(id) ON DELETE CASCADE,
    CONSTRAINT fk_concept_media_essay FOREIGN KEY (essay_id) REFERENCES essays(id) ON DELETE CASCADE,
    CONSTRAINT fk_concept_media_spark FOREIGN KEY (spark_id) REFERENCES sparks(id) ON DELETE CASCADE,
    CONSTRAINT fk_concept_media_article FOREIGN KEY (article_id) REFERENCES articles(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_concept_media_canon_id ON concept_media_links(canon_item_id);
CREATE INDEX IF NOT EXISTS idx_concept_media_podcast_id ON concept_media_links(podcast_episode_id);
CREATE INDEX IF NOT EXISTS idx_concept_media_essay_id ON concept_media_links(essay_id);
CREATE INDEX IF NOT EXISTS idx_concept_media_spark_id ON concept_media_links(spark_id);
CREATE INDEX IF NOT EXISTS idx_concept_media_article_id ON concept_media_links(article_id);
CREATE INDEX IF NOT EXISTS idx_concept_media_type ON concept_media_links(media_type);

