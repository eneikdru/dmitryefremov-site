-- Create api_keys table for A2A security schema
CREATE TABLE IF NOT EXISTS api_keys (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key_identity VARCHAR(255) CONSTRAINT uk_api_keys_key_identity UNIQUE,
    key_hash VARCHAR(255),
    scopes VARCHAR(255) DEFAULT 'SCOPE_CONTENT_READ',
    status VARCHAR(50) DEFAULT 'ACTIVE',
    rate_limit_rpm INT DEFAULT 60,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMP WITH TIME ZONE,
    last_used_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX IF NOT EXISTS idx_api_keys_identity ON api_keys(key_identity);
CREATE INDEX IF NOT EXISTS idx_api_keys_status ON api_keys(status);
