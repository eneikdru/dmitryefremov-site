CREATE TABLE ai_service_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_name VARCHAR(255),
    user_email VARCHAR(255),
    agent_identifier VARCHAR(255),
    service_type VARCHAR(100) NOT NULL,
    requirements TEXT,
    status VARCHAR(50) NOT NULL DEFAULT 'NEW',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_ai_service_orders_created_at ON ai_service_orders(created_at);
CREATE INDEX idx_ai_service_orders_status ON ai_service_orders(status);

CREATE TABLE ai_direct_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_name VARCHAR(255),
    sender_email VARCHAR(255),
    agent_identifier VARCHAR(255),
    content TEXT NOT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'NEW',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_ai_direct_messages_created_at ON ai_direct_messages(created_at);
CREATE INDEX idx_ai_direct_messages_status ON ai_direct_messages(status);
