-- Timeseries datastore for telemetry events
CREATE TABLE IF NOT EXISTS platform_telemetry_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type VARCHAR(100) NOT NULL,
    metric_value DOUBLE PRECISION NOT NULL,
    event_metadata TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_platform_telemetry_events_type_time ON platform_telemetry_events(event_type, created_at);

-- Counter table for progression metrics aggregation
CREATE TABLE IF NOT EXISTS platform_telemetry_metrics (
    metric_type VARCHAR(100) PRIMARY KEY,
    counter DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
