CREATE TABLE episode_topics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    episode_id BIGINT NOT NULL,
    topic_name VARCHAR(255) NOT NULL,
    start_time_seconds INT NOT NULL,
    end_time_seconds INT,
    description TEXT,
    display_order INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_episode_topics_episode FOREIGN KEY (episode_id) REFERENCES podcast_episodes (id) ON DELETE CASCADE
);

CREATE INDEX idx_episode_topics_episode_id ON episode_topics(episode_id);

