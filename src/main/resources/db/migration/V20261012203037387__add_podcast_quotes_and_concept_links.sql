ALTER TABLE podcast_episodes ADD COLUMN IF NOT EXISTS concept_links TEXT;

CREATE TABLE IF NOT EXISTS podcast_quotes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    episode_id BIGINT NOT NULL,
    quote_text TEXT NOT NULL,
    speaker VARCHAR(255),
    time_offset_seconds INT,
    concept_links TEXT,
    display_order INT NOT NULL DEFAULT 0,
    CONSTRAINT fk_podcast_quotes_episode FOREIGN KEY (episode_id) REFERENCES podcast_episodes (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_podcast_quotes_episode_id ON podcast_quotes(episode_id);

CREATE OR REPLACE VIEW episodes AS
SELECT
    id,
    slug,
    title,
    thesis,
    description,
    audio_url,
    media_link,
    youtube_url,
    telegram_url,
    spotify_url,
    apple_podcasts_url,
    platforms,
    concept_links,
    duration_seconds,
    published_at,
    created_at
FROM podcast_episodes;
