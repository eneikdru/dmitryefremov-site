-- Stores metadata for studio image assets and their encoded WebP/AVIF scaled variants.

CREATE TABLE IF NOT EXISTS media_assets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_key VARCHAR(255) NOT NULL UNIQUE,
    title VARCHAR(255),
    alt_text VARCHAR(512),
    source_path VARCHAR(1024) NOT NULL,
    mime_type VARCHAR(100) NOT NULL,
    original_width INT NOT NULL,
    original_height INT NOT NULL,
    original_size_bytes BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_media_assets_asset_key ON media_assets(asset_key);

CREATE TABLE IF NOT EXISTS media_asset_variants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id BIGINT NOT NULL,
    format VARCHAR(20) NOT NULL,
    breakpoint_width INT NOT NULL,
    width INT NOT NULL,
    height INT NOT NULL,
    file_path VARCHAR(1024) NOT NULL,
    file_size_bytes BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_media_asset_variants_asset FOREIGN KEY (asset_id) REFERENCES media_assets(id) ON DELETE CASCADE,
    CONSTRAINT uq_media_asset_variant UNIQUE (asset_id, format, breakpoint_width)
);

CREATE INDEX IF NOT EXISTS idx_media_asset_variants_asset_id ON media_asset_variants(asset_id);
CREATE INDEX IF NOT EXISTS idx_media_asset_variants_format_width ON media_asset_variants(format, breakpoint_width);
