CREATE TABLE agent_api_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_name VARCHAR(255) NOT NULL UNIQUE,
    token_hash VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE content_audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_id BIGINT NOT NULL,
    content_type VARCHAR(50) NOT NULL,
    content_id BIGINT NOT NULL,
    action VARCHAR(50) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_content_audit_logs_agent FOREIGN KEY (agent_id) REFERENCES agent_api_tokens (id) ON DELETE CASCADE
);

CREATE INDEX idx_content_audit_logs_agent_id ON content_audit_logs(agent_id);
CREATE INDEX idx_content_audit_logs_content ON content_audit_logs(content_type, content_id);
