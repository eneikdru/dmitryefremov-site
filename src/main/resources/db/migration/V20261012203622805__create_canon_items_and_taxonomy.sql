CREATE TABLE IF NOT EXISTS canon_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(255) NOT NULL UNIQUE,
    title VARCHAR(255) NOT NULL,
    type VARCHAR(50) NOT NULL,
    domain VARCHAR(100) NOT NULL,
    summary TEXT,
    content TEXT NOT NULL,
    published_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_canon_items_slug ON canon_items(slug);
CREATE INDEX idx_canon_items_domain ON canon_items(domain);
CREATE INDEX idx_canon_items_type ON canon_items(type);

CREATE TABLE IF NOT EXISTS canon_cross_references (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id BIGINT NOT NULL,
    target_id BIGINT NOT NULL,
    relationship_type VARCHAR(50) NOT NULL,
    description VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_canon_xref_source FOREIGN KEY (source_id) REFERENCES canon_items(id) ON DELETE CASCADE,
    CONSTRAINT fk_canon_xref_target FOREIGN KEY (target_id) REFERENCES canon_items(id) ON DELETE CASCADE,
    CONSTRAINT uk_canon_xref_source_target_rel UNIQUE (source_id, target_id, relationship_type)
);

CREATE INDEX idx_canon_xref_source ON canon_cross_references(source_id);
CREATE INDEX idx_canon_xref_target ON canon_cross_references(target_id);

