CREATE TABLE IF NOT EXISTS canon_media_links (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canon_item_id BIGINT NOT NULL,
    media_type VARCHAR(50) NOT NULL,
    media_id BIGINT NOT NULL,
    relationship_type VARCHAR(50) NOT NULL DEFAULT 'REFERENCES',
    description VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_canon_media_links_canon_item FOREIGN KEY (canon_item_id) REFERENCES canon_items(id) ON DELETE CASCADE,
    CONSTRAINT uk_canon_media_links_unique UNIQUE (canon_item_id, media_type, media_id, relationship_type)
);

CREATE INDEX idx_canon_media_links_canon_item ON canon_media_links(canon_item_id);
CREATE INDEX idx_canon_media_links_media ON canon_media_links(media_type, media_id);
